"""
Deterministic SQL Safety Validator.
Parses the SQL Abstract Syntax Tree (AST) to strictly enforce read-only semantics,
table allowlisting, rejection of dangerous functions, statement singularity, and comment stripping.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional, Set
import sqlglot
from sqlglot import exp
import sqlparse
import structlog

logger = structlog.get_logger(__name__)

# Dangerous SQL functions and procedures that must be rejected unconditionally
DISALLOWED_FUNCTIONS = {
    "pg_read_file",
    "pg_read_binary_file",
    "pg_write_file",
    "pg_write_binary_file",
    "pg_ls_dir",
    "pg_stat_file",
    "pg_sleep",
    "pg_terminate_backend",
    "pg_cancel_backend",
    "dblink",
    "dblink_exec",
    "lo_import",
    "lo_export",
    "system",
    "exec",
    "eval",
    "query_to_xml",
    "cursor",
    "load_file",
    "sys_eval",
}

# Dangerous statement types that must be rejected
DISALLOWED_EXPRESSIONS = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Create,
    exp.Alter,
    exp.Drop,
    exp.Command,
    exp.Pragma,
    exp.Grant,
)



@dataclass
class ValidationResult:
    is_valid: bool
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    tables_referenced: List[str] = field(default_factory=list)
    sanitized_sql: Optional[str] = None


class SQLValidator:
    """
    Validates that untrusted SQL generated by an LLM or user is strictly:
    1. A single statement
    2. A pure SELECT statement (or WITH... SELECT)
    3. Referencing only allowlisted tables
    4. Free of DDL/DML, into clauses, dangerous system functions, and prohibited catalog access
    """

    def __init__(self, allowed_tables: Optional[Set[str]] = None, dialect: str = "postgres"):
        self.allowed_tables = {t.lower() for t in (allowed_tables or set())}
        self.dialect = dialect

    def validate(self, sql_query: str) -> ValidationResult:
        errors: List[str] = []
        warnings: List[str] = []
        tables_found: Set[str] = set()

        if not sql_query or not sql_query.strip():
            return ValidationResult(is_valid=False, errors=["Empty SQL query provided"])

        # 1. Multi-statement check via sqlparse
        parsed_statements = sqlparse.parse(sql_query)
        # Filter out empty statements (e.g. trailing whitespaces/semicolons)
        non_empty = [s for s in parsed_statements if s.get_type() != "UNKNOWN" or str(s).strip()]
        if len(non_empty) > 1:
            return ValidationResult(
                is_valid=False,
                errors=["Multiple SQL statements detected. Exactly one statement is permitted."],
            )

        # 2. Parse AST via sqlglot
        try:
            ast_list = sqlglot.parse(sql_query, read=self.dialect)
            if not ast_list:
                return ValidationResult(is_valid=False, errors=["Failed to parse SQL into valid AST"])
            if len(ast_list) > 1:
                return ValidationResult(
                    is_valid=False,
                    errors=["Multiple AST expressions detected. Only a single query is allowed."],
                )
            root = ast_list[0]
        except Exception as e:
            return ValidationResult(
                is_valid=False,
                errors=[f"SQL syntax error: {str(e)}"],
            )

        # 3. Check statement type: Must be Select or Expression containing Select (CTE/Union)
        if isinstance(root, DISALLOWED_EXPRESSIONS):
            return ValidationResult(
                is_valid=False,
                errors=[f"Statement type '{type(root).__name__}' is strictly forbidden. Only read-only SELECT queries are permitted."],
            )

        if not isinstance(root, (exp.Select, exp.Union)):
            return ValidationResult(
                is_valid=False,
                errors=[f"Invalid query type '{type(root).__name__}'. Only SELECT statements are permitted."],
            )

        # 4. Check for SELECT INTO
        if root.find(exp.Into):
            errors.append("SELECT INTO clauses are prohibited.")

        # 5. Walk AST to inspect tables and functions
        for node in root.walk():
            # Check for illegal statement nodes nested inside subqueries
            if isinstance(node, DISALLOWED_EXPRESSIONS):
                errors.append(f"Nested modifying operation detected: {type(node).__name__}")

            # Check functions
            if isinstance(node, (exp.Anonymous, exp.Func)):
                func_name = (node.name or "").lower()
                if func_name in DISALLOWED_FUNCTIONS:
                    errors.append(f"Disallowed function call detected: '{func_name}'")

            # Collect referenced tables
            if isinstance(node, exp.Table):
                table_name = node.name.lower()
                # Ignore CTE aliases defined in WITH clause
                tables_found.add(table_name)

        # Filter out CTE names from tables_found
        cte_names = set()
        for with_clause in root.find_all(exp.With):
            for cte in with_clause.expressions:
                if cte.alias:
                    cte_names.add(cte.alias.lower())

        actual_tables = tables_found - cte_names

        # 6. Validate against allowed tables if allowlist is provided
        if self.allowed_tables:
            for table in actual_tables:
                if table not in self.allowed_tables:
                    errors.append(
                        f"Access to table '{table}' is prohibited. Allowed tables in this dataset: {sorted(list(self.allowed_tables))}"
                    )

        # Generate standardized clean SQL representation without comments
        try:
            sanitized_sql = root.sql(dialect=self.dialect, comments=False)
        except Exception:
            sanitized_sql = sql_query.strip()

        is_valid = (len(errors) == 0)
        return ValidationResult(
            is_valid=is_valid,
            errors=errors,
            warnings=warnings,
            tables_referenced=sorted(list(actual_tables)),
            sanitized_sql=sanitized_sql if is_valid else None,
        )
