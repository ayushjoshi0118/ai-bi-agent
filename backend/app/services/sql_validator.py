"""
Deterministic, Dialect-Aware Fail-Closed SQL Safety Validator.
Parses the SQL Abstract Syntax Tree (AST) to strictly enforce read-only semantics,
table allowlisting, rejection of dangerous functions, statement singularity,
CTE data-modification detection, and system catalog access prohibition.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional, Set
import sqlglot
from sqlglot import exp
import sqlparse
import structlog

logger = structlog.get_logger(__name__)

# System schemas that can never be queried by untrusted analytics queries
FORBIDDEN_SCHEMAS = {
    "pg_catalog",
    "information_schema",
    "pg_toast",
    "sys",
    "sqlite_master",
    "sqlite_schema",
}

# System and internal tables that cannot be queried under any circumstance
FORBIDDEN_SYSTEM_TABLES = {
    "pg_user",
    "pg_shadow",
    "pg_authid",
    "pg_database",
    "pg_tables",
    "pg_stat_activity",
    "pg_roles",
    "pg_group",
    "pg_settings",
    "pg_proc",
    "pg_class",
    "sqlite_master",
    "sqlite_temp_master",
    "sqlite_sequence",
    "sqlite_stat1",
    "sqlite_stat2",
    "sqlite_stat3",
    "sqlite_stat4",
}

# Dangerous SQL functions that must be rejected unconditionally
DISALLOWED_FUNCTIONS = {
    # File & OS access
    "pg_read_file",
    "pg_read_binary_file",
    "pg_write_file",
    "pg_write_binary_file",
    "pg_ls_dir",
    "pg_stat_file",
    "load_file",
    "readfile",
    "writefile",
    "edit",
    # Sleep & DoS
    "pg_sleep",
    "pg_sleep_for",
    "pg_sleep_until",
    "pg_terminate_backend",
    "pg_cancel_backend",
    # Remote connections & DBLINK
    "dblink",
    "dblink_exec",
    "dblink_connect",
    "dblink_send_query",
    "dblink_get_result",
    # Large Objects
    "lo_import",
    "lo_export",
    "lo_create",
    "lo_unlink",
    "lo_open",
    # Execution & System
    "system",
    "exec",
    "eval",
    "sys_eval",
    "sys_exec",
    "passthru",
    "shell_exec",
    # Data Exfiltration
    "query_to_xml",
    "query_to_xml_and_xmlschema",
    "database_to_xml",
    "table_to_xml",
    # Session / Config Manipulation
    "set_config",
    "current_setting",
    "pg_reload_conf",
    "pg_rotate_logfile",
    "pg_create_restore_point",
    # Diagnostic / Info Leaks
    "pg_backend_pid",
    "inet_server_addr",
    "inet_client_addr",
    "cursor",
}

# Prohibited statement expressions across all branches and subqueries
DISALLOWED_EXPRESSIONS = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Merge,
    exp.Create,
    exp.Alter,
    exp.Drop,
    exp.Command,
    exp.Pragma,
    exp.Grant,
    exp.Revoke,
    exp.Transaction,
    exp.Commit,
    exp.Rollback,
    exp.Set,
    exp.Show,
    exp.Describe,
    exp.Analyze,
    exp.Lock,
    exp.Into,
)


@dataclass
class ValidationResult:
    is_valid: bool
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    tables_referenced: List[str] = field(default_factory=list)
    sanitized_sql: Optional[str] = None


class SQLValidator:
    """
    Hardened, fail-closed SQL policy validator.
    Validates that untrusted SQL generated by an LLM or user is strictly:
    1. A single statement
    2. A pure SELECT or UNION query
    3. Referencing exclusively allowlisted tables
    4. Prohibiting DDL, DML, CTE data modification, into clauses, dangerous system functions,
       system catalog schemas, and multi-statement injection.
    """

    def __init__(self, allowed_tables: Optional[Set[str]] = None, dialect: str = "postgres"):
        self.allowed_tables = {t.lower().strip() for t in (allowed_tables or set())}
        self.dialect = "postgres" if dialect in ("postgres", "postgresql") else "sqlite"

    def validate(self, sql_query: str) -> ValidationResult:
        errors: List[str] = []
        warnings: List[str] = []
        tables_found: Set[str] = set()

        if not sql_query or not sql_query.strip():
            return ValidationResult(is_valid=False, errors=["Empty SQL query provided"])

        raw_query = sql_query.strip()

        # 1. Multi-statement check via sqlparse
        parsed_statements = sqlparse.parse(raw_query)
        non_empty = [s for s in parsed_statements if s.get_type() != "UNKNOWN" or str(s).strip()]
        if len(non_empty) > 1:
            return ValidationResult(
                is_valid=False,
                errors=["Multiple SQL statements detected. Exactly one statement is permitted."],
            )

        # 2. Parse Abstract Syntax Tree via sqlglot
        try:
            ast_list = sqlglot.parse(raw_query, read=self.dialect)
            if not ast_list:
                return ValidationResult(is_valid=False, errors=["Failed to parse SQL into valid AST"])
            if len(ast_list) > 1:
                return ValidationResult(
                    is_valid=False,
                    errors=["Multiple AST expressions detected. Only a single query is allowed."],
                )
            root = ast_list[0]
        except Exception as e:
            return ValidationResult(
                is_valid=False,
                errors=[f"SQL syntax error: {str(e)}"],
            )

        # 3. Check root statement type: Must strictly be Select or Union
        if isinstance(root, DISALLOWED_EXPRESSIONS):
            return ValidationResult(
                is_valid=False,
                errors=[f"Statement type '{type(root).__name__}' is strictly forbidden. Only read-only SELECT queries are permitted."],
            )

        if not isinstance(root, (exp.Select, exp.Union)):
            return ValidationResult(
                is_valid=False,
                errors=[f"Invalid query type '{type(root).__name__}'. Only SELECT statements are permitted."],
            )

        # 4. Strict CTE (WITH clause) validation
        cte_aliases: Set[str] = set()
        for with_clause in root.find_all(exp.With):
            for cte in with_clause.expressions:
                if isinstance(cte, exp.CTE):
                    if cte.alias:
                        cte_aliases.add(cte.alias.lower().strip())
                    # In PostgreSQL, CTEs can contain data-modifying statements:
                    # WITH del AS (DELETE FROM tbl RETURNING *) SELECT * FROM del
                    if not isinstance(cte.this, (exp.Select, exp.Union)):
                        errors.append(
                            f"CTE '{cte.alias}' contains non-read-only operation '{type(cte.this).__name__}'"
                        )

        # 5. Walk entire AST to inspect all nodes, functions, and table references
        for node in root.walk():
            # Check for disallowed operations nested in subqueries or expressions
            if isinstance(node, DISALLOWED_EXPRESSIONS):
                errors.append(f"Forbidden operation detected: '{type(node).__name__}'")

            # Check for SELECT INTO
            if isinstance(node, exp.Into):
                errors.append("SELECT INTO clauses are prohibited.")

            # Check for disallowed functions
            if isinstance(node, (exp.Anonymous, exp.Func)):
                func_name = (node.name or "").lower().strip()
                if func_name in DISALLOWED_FUNCTIONS:
                    errors.append(f"Disallowed function call detected: '{func_name}'")

            # Check table references
            if isinstance(node, exp.Table):
                table_name = (node.name or "").lower().strip()
                schema_name = (node.db or "").lower().strip()

                # Block forbidden system schemas
                if schema_name in FORBIDDEN_SCHEMAS:
                    errors.append(f"Access to system schema '{schema_name}' is strictly prohibited.")

                # Block forbidden system tables
                if table_name in FORBIDDEN_SYSTEM_TABLES:
                    errors.append(f"Access to system table '{table_name}' is strictly prohibited.")

                # Ignore genuine CTE aliases
                if table_name not in cte_aliases:
                    tables_found.add(table_name)

        # 6. Validate against allowed tables allowlist (fail-closed)
        if self.allowed_tables:
            for table in tables_found:
                if table not in self.allowed_tables:
                    errors.append(
                        f"Access to table '{table}' is prohibited. Permitted tables: {sorted(list(self.allowed_tables))}"
                    )
        elif not errors and not tables_found:
            # Query has no tables (e.g. SELECT 1) - permitted if no other errors
            pass

        # 7. Generate clean canonical sanitized SQL without comments or trailing semicolons
        try:
            sanitized_sql = root.sql(dialect=self.dialect, comments=False).rstrip(";").strip()
        except Exception:
            sanitized_sql = raw_query.rstrip(";").strip()

        is_valid = (len(errors) == 0)
        return ValidationResult(
            is_valid=is_valid,
            errors=errors,
            warnings=warnings,
            tables_referenced=sorted(list(tables_found)),
            sanitized_sql=sanitized_sql if is_valid else None,
        )
